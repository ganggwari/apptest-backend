--      300m 미만 CCTV / 300 이상 500 미만 FINAL_LPR(진입직전) / 500 이상 2000 이하 APPROACH_LPR(접근 길목) / 2000 초과 CCTV
--      (이 시드의 ITS CCTV 는 모두 반경 1000m 이내라 2000 초과는 없음)
UPDATE camera c
SET dist = d.m,
    role = (CASE WHEN d.m >= 300 AND d.m < 500 THEN 'FINAL_LPR'
                 WHEN d.m >= 500 AND d.m <= 2000 THEN 'APPROACH_LPR'
                 ELSE 'CCTV' END)::camera_role
FROM (
  SELECT c2.id,
         ROUND(6371000 * 2 * ASIN(SQRT(POWER(SIN(RADIANS(c2.lat - u.lat) / 2), 2)
               + COS(RADIANS(u.lat)) * COS(RADIANS(c2.lat)) * POWER(SIN(RADIANS(c2.lng - u.lng) / 2), 2))))::int AS m
    FROM camera c2 JOIN underpass u ON u.id = c2.underpass_id
   WHERE c2.its_cctv_id IS NOT NULL
) d
WHERE c.id = d.id;

